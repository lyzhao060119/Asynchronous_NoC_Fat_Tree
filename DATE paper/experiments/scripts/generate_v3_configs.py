def dump(path: Path, obj: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2) + "\n", encoding="utf-8")


def primitive(
    design_id: str,
    family: str,
    level: int,
    child: int,
    parent: int,
    *,
    mesh: bool,
    async_design: bool,
    adapters: int,
    ports: int,
    max_fanin: int,
    mutex: list[int],
    paper_role: str,
    adapter: str = "dc_cmr_router",
    clock_ns=None,
) -> dict:
    return {
        "schema": "date-v3-design-v1",
        "design_id": design_id,
        "kind": "router_primitive",
        "family": family,
        "nodes": None,
        "async": async_design,
        "routing": "mesh" if mesh else "quadtree",
        "lane_profile": "%d-%d" % (child, parent),
        "top_mesh_lanes": None,
        "cluster_grid": None,
        "router_primitives": [
            {
                "primitive_id": design_id.lower(),
                "level": level,
                "child_lanes": child,
                "parent_lanes": parent,
                "use_mesh_routing": mesh,
                "count": 1,
            }
        ],
        "expected_structure": {
            "routers": 1,
            "ports": ports,
            "adapters": adapters,
            "interlevel_fifos": 0,
            "top_ports": 0,
            "max_opm_fanin": max_fanin,
            "mutex_widths": mutex,
        },
        "flit_width_bits": 28,
        "buffer_slots": 5,
        "no_uturn": True,
        "interlevel_fifo": "n/a",
        "delay_recipe": dict(LOCKED),
        "clock_ns": clock_ns,
        "hrep_policy": False,
        "shares_netlist_with": None,
        "adapter": adapter,
        "paper_role": paper_role,
        "paper_eligible_default": True,
        "notes": "Table I / calibration primitive. Same CMR microarchitecture; geometry only.",
    }


